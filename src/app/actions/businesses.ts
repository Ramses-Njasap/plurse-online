/** Called when the Payment modal fires its callback or webhook verifies completion */
export async function activateAccessKeyAction(keyId: string): Promise<{ success: boolean; message?: string }> {
    const { error } = await supabaseAdmin
        .from("access_keys")
        .update({ is_active: true, activated_at: new Date().toISOString() })
        .eq("id", keyId);

    if (error) return { success: false, message: error.message };
    return { success: true };
}


export interface DeleteResult {
    id: string;
    name: string;
    success: boolean;
    action: "deleted" | "unlinked" | "failed";
    message: string;
}

/**
 * Evaluates deletion/unlinking rules on a single business instance.
 */
export async function deleteOrUnlinkBusinessAction(businessId: string): Promise<DeleteResult> {
    const currentUser = await whichUser.info;
    if (!currentUser) {
        return {
            id: businessId,
            name: "Unknown",
            success: false,
            action: "failed",
            message: "Authentication expired. Please log in again."
        };
    }

    try {
        // Fetch the target business with its access key and channel partner relations
        const { data: business, error: fetchError } = await supabaseAdmin
            .from("businesses")
            .select(`
                id,
                name,
                owner_id,
                access_key:access_keys!access_key_id (
                    id,
                    key_type,
                    created_on,
                    from_company,
                    channel_partner_id,
                    channel_partner:channel_partners!channel_partner_id (
                        user_id
                    )
                )
            `)
            .eq("id", businessId)
            .single();

        if (fetchError || !business) {
            return {
                id: businessId,
                name: "Unknown",
                success: false,
                action: "failed",
                message: "Business record not found in the database."
            };
        }

        const accessKey: any = business.access_key;
        const businessName = business.name;

        if (!accessKey) {
            return {
                id: businessId,
                name: businessName,
                success: false,
                action: "failed",
                message: "This business is not currently tied to an active access key structure."
            };
        }

        const { from_company, channel_partner_id, key_type, created_on } = accessKey;
        const partnerUserId = accessKey.channel_partner?.user_id || null;

        // ── CASE 3: Unlinked Business (channel_partner_id is NOT NULL and from_company is TRUE) ──
        if (channel_partner_id !== null && from_company === true) {
            return {
                id: businessId,
                name: businessName,
                success: false,
                action: "failed",
                message: `"${businessName}" has already been unlinked by its channel partner.`
            };
        }

        // ── CASE 1: Channel Partner Context (from_company is FALSE, channel_partner_id is NOT NULL) ──
        if (from_company === false && channel_partner_id !== null && partnerUserId === currentUser.id) {
            const createdDate = new Date(created_on);

            // 3-month threshold calculation
            const threeMonthsAgo = new Date();
            threeMonthsAgo.setMonth(threeMonthsAgo.getMonth() - 3);

            const fiveMinutesAgo = new Date().setMinutes(new Date().getMinutes() - 5);

            if (key_type === "TRIAL") {
                return {
                    id: businessId,
                    name: businessName,
                    success: false,
                    action: "failed",
                    message: `Trial businesses ("${businessName}") cannot be deleted or unlinked. They expire automatically.`
                };
            }

            if (key_type === "LIFETIME") {
                if (createdDate.getTime() > fiveMinutesAgo) {
                    return {
                        id: businessId,
                        name: businessName,
                        success: false,
                        action: "failed",
                        message: `Lifetime contracts must remain active for at least 3 months before unlinking. "${businessName}" is too new.`
                    };
                } else {
                    // Unlink by setting from_company to true (preserve channel_partner_id)
                    const { error: unlinkError } = await supabaseAdmin
                        .from("access_keys")
                        .update({ from_company: true })
                        .eq("id", accessKey.id);

                    if (unlinkError) throw unlinkError;

                    return {
                        id: businessId,
                        name: businessName,
                        success: true,
                        action: "unlinked",
                        message: `Successfully unlinked "${businessName}" from your partner panel.`
                    };
                }
            }
        }

        // ── CASE 2: Self-Owned Business (channel_partner_id is NULL and from_company is TRUE) ──
        if (channel_partner_id === null && from_company === true) {
            const { error: deleteError } = await supabaseAdmin
                .from("businesses")
                .delete()
                .eq("id", businessId);

            if (deleteError) throw deleteError;

            return {
                id: businessId,
                name: businessName,
                success: true,
                action: "deleted",
                message: `Successfully deleted your self-managed business "${businessName}".`
            };
        }

        // Default Guard
        return {
            id: businessId,
            name: businessName,
            success: false,
            action: "failed",
            message: "You do not have administrative permissions to delete or modify this business."
        };

    } catch (err: any) {
        console.error(`Error processing delete/unlink action for ${businessId}:`, err);
        return {
            id: businessId,
            name: "System Error",
            success: false,
            action: "failed",
            message: err.message || "An unexpected database transaction error occurred."
        };
    }
}

/**
 * Iterates through selected business IDs and runs the deletion/unlinking action on each.
 */
export async function deleteOrUnlinkBusinessesBulkAction(ids: string[]): Promise<DeleteResult[]> {
    const results: DeleteResult[] = [];
    for (const id of ids) {
        const result = await deleteOrUnlinkBusinessAction(id);
        results.push(result);
    }
    return results;
}