// Define a safe response envelope
export type FetchBusinessesResponse =
    | { success: true; data: Business[] }
    | { success: false; errorType: "UNAUTHORIZED" | "DATABASE_ERROR"; message: string };

export async function fetchAuthenticatedBusinesses(): Promise<FetchBusinessesResponse> {
    const supabase = createClient(
        process.env.SUPABASE_URL!,
        process.env.SUPABASE_SERVICE_ROLE_KEY!
    );

    const currentUser = await whichUser.info;
    if (!currentUser) {
        return {
            success: false,
            errorType: "UNAUTHORIZED",
            message: "Your session has expired or you are not logged in."
        };
    }

    const userId = currentUser.id;

    try {
        // Step 1: Look up the channel partner record using the logged-in user's profile ID
        const { data: partnerRecord, error: partnerError } = await supabase
            .from("channel_partners")
            .select("id")
            .eq("user_id", userId)
            .maybeSingle();

        if (partnerError) {
            console.error("Error identifying partner context:", partnerError);
            return { success: false, errorType: "DATABASE_ERROR", message: "Failed to verify partner profile." };
        }

        // Step 2: Grab all access keys generated by this channel partner
        // CRITICAL: We must filter for keys where `from_company` is strictly FALSE.
        // This ensures unlinked keys (which are now from_company = true) do not populate the partner's list.
        let partnerKeyIds: string[] = [];
        if (partnerRecord) {
            const { data: keysData, error: keysError } = await supabase
                .from("access_keys")
                .select("id")
                .eq("channel_partner_id", partnerRecord.id)
                .eq("from_company", false);

            if (keysError) {
                console.error("Error fetching partner keys:", keysError);
                return { success: false, errorType: "DATABASE_ERROR", message: "Failed to retrieve partner keys." };
            }

            if (keysData) {
                partnerKeyIds = keysData.map((k) => k.id).filter(Boolean);
            }
        }

        // Step 3: Query the businesses base table with explicit foreign key names
        let query = supabase
            .from("businesses")
            .select(`
                id,
                owner_id,
                name,
                country,
                region_city,
                access_key_id,
                created_on,
                updated_on,
                manager_profile:user_profiles!owner_id (
                    *,
                    manager_user:users!id (*) 
                ),
                access_key:access_keys!access_key_id (
                    id,
                    key_code,
                    key_type,
                    amount,
                    deduct_trial_fee,
                    expires_at,
                    activated_at,
                    created_on,
                    channel_partner_id,
                    channel_partner:channel_partners!channel_partner_id (
                        id,
                        user_id,
                        valid_from,
                        valid_to,
                        amount,
                        profile:user_profiles!user_id (
                            *,
                            user:users!id (*)
                        )
                    )
                )
            `);


        // Step 4: Run the OR logic cleanly with quoted UUID array signatures
        if (partnerKeyIds.length > 0) {
            const quotedKeyIds = partnerKeyIds.map((id) => `"${id}"`).join(",");
            query = query.or(`owner_id.eq.${userId},access_key_id.in.(${quotedKeyIds})`);
        } else {
            query = query.eq("owner_id", userId);
        }

        const { data, error } = await query;

        if (error) {
            console.error("Database query exception:", error);
            return { success: false, errorType: "DATABASE_ERROR", message: "Failed to retrieve records." };
        }

        // Step 5: Format properties into flat structures matching expectations
        const formattedBusinesses: Business[] = (data || []).map((b: any) => {
            const nestedPartnerArray = b.access_key?.channel_partner;
            const nestedPartner = Array.isArray(nestedPartnerArray)
                ? nestedPartnerArray[0]
                : nestedPartnerArray || null;

            return {
                ...b,
                manager_profile: b.manager_profile || null,
                manager_user: b.manager_profile?.manager_user || null,
                channel_partner: nestedPartner ? {
                    ...nestedPartner,
                    profile: nestedPartner.profile || null,
                    user: nestedPartner.profile?.user || null
                } : null,
            };
        });

        return { success: true, data: formattedBusinesses };

    } catch (e) {
        console.error("Unexpected parsing exception:", e);
        return { success: false, errorType: "DATABASE_ERROR", message: "An unexpected error occurred." };
    }
}


const supabaseAdmin = createClient(
    process.env.SUPABASE_URL!,
    process.env.SUPABASE_SERVICE_ROLE_KEY!
);

export type ProvisionBusinessResponse =
    | { success: true; business: Business; accessKey: AccessKey }
    | { success: false; message: string };

interface ProvisionBusinessPayload {
    // Phase 1 (Wizard Step 1 & 2): Manager Credentials & Profile
    email: string;
    phone: string;
    managerFullName: string;
    managerDob: string;
    managerCountry: string;
    managerCity: string;

    // Phase 1 (Wizard Step 3): Business Specs
    businessName: string;
    businessCountry: string;
    businessCity: string;

    // Phase 2 (Key Form): Target License Configuration
    key_code: string;
    key_type: "TRIAL" | "LIFETIME";
    amount: number;
    deduct_trial_fee: boolean;

    // Self-owned business flag (true = user is creating a business for themselves, false = channel partner creating for another)
    isSelfOwned: boolean;
}

type RawBusinessRow = Omit<Business, 'manager_user' | 'manager_profile' | 'access_key' | 'channel_partners'>;

export async function provisionPendingBusinessAction(payload: ProvisionBusinessPayload): Promise<ProvisionBusinessResponse> {
    const operator = await whichUser.info;
    if (!operator) {
        return { success: false, message: "Unauthorized. Channel partner session required." };
    }

    const calculatedExpiration = payload.key_type === "TRIAL"
        ? new Date(Date.now() + TRIAL_PERIOD_DAYS * 24 * 60 * 60 * 1000).toISOString()
        : null;

    try {
        // Execute the single, unified database transaction
        const { data, error } = await supabaseAdmin.rpc("provision_business_transaction", {
            p_email: payload.isSelfOwned ? operator.email : payload.email,
            p_phone: payload.isSelfOwned ? (operator.phone || "") : payload.phone,
            p_manager_full_name: payload.managerFullName,
            p_manager_dob: payload.managerDob || null,
            p_manager_country: payload.managerCountry,
            p_manager_city: payload.managerCity,
            p_business_name: payload.businessName,
            p_business_country: payload.businessCountry,
            p_business_city: payload.businessCity,
            p_key_code: payload.key_code,
            p_key_type: payload.key_type,
            p_amount: payload.amount,
            p_deduct_trial_fee: payload.deduct_trial_fee,
            p_calculated_expiration: calculatedExpiration,
            p_operator_user_id: operator.id,
            p_is_self_owned: payload.isSelfOwned
        });

        if (error) throw error;
        if (!data || data.success === false) {
            return { success: false, message: data?.message || "Failed to provision business records." };
        }

        const runtimeDate = data.created_on;

        // Construct standard application domain models back to client view layer
        const returnBusiness: Business = {
            id: data.business_id,
            name: payload.businessName,
            country: payload.businessCountry,
            region_city: payload.businessCity,
            owner_id: data.business_user_id,
            access_key_id: data.access_key_id,
            created_on: runtimeDate,
            updated_on: runtimeDate,
            manager_user: {
                id: data.business_user_id,
                email: payload.isSelfOwned ? operator.email : payload.email.trim().toLowerCase(),
                phone: payload.isSelfOwned ? (operator.phone || "") : payload.phone.trim(),
                is_business: true,
                is_individual: false,
                is_active: true,
                email_verified: false,
                phone_verified: false,
                created_on: runtimeDate,
                updated_on: runtimeDate,
                is_deleted: false,
                is_banned: false
            },
            manager_profile: {
                id: data.business_user_id,
                user_id: data.business_user_id,
                full_name: payload.managerFullName,
                date_of_birth: payload.managerDob,
                country: payload.managerCountry,
                region_city: payload.managerCity,
                is_channel_partner: payload.isSelfOwned,
                created_on: runtimeDate,
                updated_on: runtimeDate
            },
            access_key: {
                id: data.access_key_id,
                key_code: payload.key_code,
                key_type: payload.key_type,
                is_active: false,
                activated_at: null,
                expires_at: calculatedExpiration,
                amount: payload.amount,
                deduct_trial_fee: payload.deduct_trial_fee,
                created_on: runtimeDate,
            },
            channel_partner: null
        };

        const returnKey: AccessKey = {
            id: data.access_key_id,
            key_code: payload.key_code,
            key_type: payload.key_type,
            is_active: false,
            activated_at: null,
            expires_at: runtimeDate,
            amount: payload.amount,
            deduct_trial_fee: payload.deduct_trial_fee,
            created_on: runtimeDate,
            business: returnBusiness,
        };

        return { success: true, business: returnBusiness, accessKey: returnKey };

    } catch (err: any) {
        console.error("Critical error inside transactional business orchestration:", err);
        return { success: false, message: err.message || "An unexpected system error occurred." };
    }
}


